/// egui's embedded fonts: (font file, its notice file, name, license).
const FONTS: [(&str, &str, &str, &str); 4] = [
    ("Ubuntu-Light.ttf", "UFL.txt", "Ubuntu Light", "Ubuntu-font-1.0"),
    ("Hack-Regular.ttf", "Hack-Regular.txt", "Hack Regular", "MIT AND Bitstream-Vera"),
    ("NotoEmoji-Regular.ttf", "OFL.txt", "Noto Emoji", "OFL-1.1"),
    ("emoji-icon-font.ttf", "emoji-icon-font-mit-license.txt", "emoji-icon-font", "MIT"),
];
/// Licenses the font entries cover, so the fonts' crate needs no text for them.
const FONT_LICENSES: [&str; 2] = ["OFL-1.1", "Ubuntu-font-1.0"];

struct Entry {
    kind: &'static str,
    name: String,
    version: String,
    license: String,
    /// The platforms whose builds include it, as in TARGETS: "Windows, Linux".
    platforms: String,
    source: String,
    text: String,
}

fn main() -> ExitCode {
    let check = env::args().any(|a| a == "--check");
    let root = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("..").join("..");
    let cargo = |args: &[&str]| {
        let output = Command::new(env::var_os("CARGO").unwrap_or_else(|| "cargo".into()))
            .current_dir(&root)
            .args(args)
            .args(["--locked", "--offline"])
            .output()
            .expect("run cargo");
        assert!(output.status.success(), "cargo {args:?} failed: {}", String::from_utf8_lossy(&output.stderr));
        output.stdout
    };
    // The crates the shipped programs compile for each target, with the platforms that
    // compile them, and features resolved as the build does; `cargo metadata` would also
    // count features only tests turn on.
    let mut compiled: BTreeMap<(String, String), Vec<&str>> = BTreeMap::new();
    for (platform, target) in TARGETS {
        let mut tree = vec!["tree", "-e", "normal", "--prefix", "none", "--format", "{p}", "--target", target];
        for package in SHIPPED {
            tree.extend(["-p", package]);
        }
        tree.extend(["--features", "rocket-integrations/runtime"]);
        let mut crates: HashSet<(String, String)> = String::from_utf8_lossy(&cargo(&tree))
            .lines()
            .filter_map(|line| {
                let mut words = line.split_whitespace();
                let name = words.next()?;
                let version = words.next()?.strip_prefix('v')?;
                Some((name.to_owned(), version.to_owned()))
            })
            .collect();
        // This build dependency supplies the C sources statically linked into the Lua worker.
        if crates.iter().any(|(name, _)| name == "mlua-sys") {
            crates.insert(("lua-src".into(), "551.1.0".into()));
        }
        for key in crates {
            compiled.entry(key).or_default().push(platform);
        }
    }
    let metadata: Value =
        serde_json::from_slice(&cargo(&["metadata", "--format-version", "1", "--features", "rocket-integrations/runtime"])).expect("cargo metadata JSON");
    let apache = read_text(&root.join("LICENSE-APACHE"));

    let members: HashSet<&str> = array(&metadata["workspace_members"]).iter().map(string).collect();
    let mut crates: Vec<&Value> = array(&metadata["packages"])
        .iter()
        .filter(|p| !members.contains(string(&p["id"])))
        .filter(|p| compiled.contains_key(&(string(&p["name"]).to_owned(), string(&p["version"]).to_owned())))
        .collect();
    let first_party = compiled.keys().filter(|(name, _)| name.starts_with("rocket-")).count();
    assert_eq!(crates.len() + first_party, compiled.len(), "every compiled crate has package metadata");
    crates.sort_by(|a, b| (string(&a["name"]), string(&a["version"])).cmp(&(string(&b["name"]), string(&b["version"]))));

    let mut entries = Vec::new();
    let mut fonts = Vec::new();
    for package in crates {
        let name = string(&package["name"]);
        let version = string(&package["version"]);
        let license = package["license"].as_str().unwrap_or_default();
        assert!(!license.is_empty(), "{name} {version} declares no license expression");
        let directory = Path::new(string(&package["manifest_path"])).parent().expect("package directory");
        let authors: Vec<String> = array(&package["authors"])
            .iter()
            .map(|a| string(a).split(" <").next().unwrap_or_default().trim().to_owned())
            .filter(|a| !a.is_empty())
            .collect();
        let authors = if authors.is_empty() { format!("the {name} authors") } else { authors.join(", ") };
        let platforms = compiled[&(name.to_owned(), version.to_owned())].join(", ");
        let mut text = notice(directory, license, &authors, &apache)
            .unwrap_or_else(|missing| panic!("{name} {version}: no text for {missing}; add it to this generator"));
        if name == "epaint_default_fonts" {
            fonts = egui_fonts(directory, version, &platforms);
            text.push_str("\n\nThe fonts it includes have their own entries.");
        }
        if choices(license).iter().any(|(chosen, _)| chosen == "MPL-2.0") {
            // MPL-2.0 section 3.2(a): whoever receives the program must be told how to get
            // the source of the covered files. That is the crates.io package, as long as
            // Cargo builds it from there unchanged rather than from a patch or a fork.
            assert_eq!(string(&package["source"]), CRATES_IO, "{name} {version}: say where this MPL-2.0 source is");
            text = format!(
                "Rocket includes {name} {version} unmodified. Its source code is available from crates.io:\n\
                 https://crates.io/crates/{name}/{version}\n\
                 Download: https://static.crates.io/crates/{name}/{version}/download\n\n{text}"
            );
        }
        if name == "lua-src" {
            // The wrapper's LICENSE carries an older Lua notice; also include
            // the exact copyright/permission block of the C version we compile.
            let header=read_text(&directory.join("lua-5.5.1/lua.h"));
            let start=header.rfind("Copyright (C) 1994-2026 Lua.org, PUC-Rio.").expect("Lua C copyright");
            let notice:Vec<_>=header[start..].lines().take_while(|line|!line.contains("********")).map(|line|line.trim_start_matches('*').trim_start()).collect();
            let notice=notice.join("\n");
            assert!(notice.contains("Permission is hereby granted"));
            text.push_str("\n\n--- Lua 5.5.1 C sources: lua.h ---\n\n");
            text.push_str(&notice);
        }
        entries.push(Entry {
            kind: "crate",
            name: name.to_owned(),
            version: version.to_owned(),
            license: license.to_owned(),
            platforms,
            source: package["repository"].as_str().unwrap_or_default().to_owned(),
            text,
        });
    }
    assert!(!fonts.is_empty(), "egui's fonts were not found");
    entries.extend(fonts);
    entries.push(conpty(&root));

    let text = render(&entries);
    let path = root.join(FILE_NAME);
    let crates = entries.iter().filter(|e| e.kind == "crate").count();
    let per_platform: Vec<String> = TARGETS
        .iter()
        .map(|(platform, _)| {
            let on = entries.iter().filter(|e| e.kind == "crate" && e.platforms.split(", ").any(|p| p == *platform));
            format!("{} on {platform}", on.count())
        })
        .collect();
    let summary = format!("{crates} crates ({}), {} other entries", per_platform.join(", "), entries.len() - crates);
    if check {
        let current = fs::read_to_string(&path).unwrap_or_default().replace("\r\n", "\n");
        if current != text {
            eprintln!("{FILE_NAME} is out of date; run `cargo run -p rocket-ui --example third_party_notices`.");
            return ExitCode::FAILURE;
        }
        println!("{FILE_NAME} is current: {summary}.");
        return ExitCode::SUCCESS;
    }
    fs::write(&path, text).expect("write the notices");
    println!("Wrote {FILE_NAME}: {summary}.");
    ExitCode::SUCCESS
}

/// A crate's notice: the license files it ships, or, when it ships none, the standard
/// text of the license Rocket uses with its declared authors. Under an OR choice that
/// offers MIT, Rocket uses MIT, so the other choices' files are left out.
fn notice(directory: &Path, expression: &str, authors: &str, apache: &str) -> Result<String, String> {
    let parts = choices(expression);
    let mut files: Vec<(String, String)> = fs::read_dir(directory)
        .map_err(|e| e.to_string())?
        .flatten()
        .filter(|e| e.file_type().is_ok_and(|t| t.is_file()))
        .filter_map(|e| {
            let name = e.file_name().to_string_lossy().into_owned();
            let upper = name.to_uppercase();
            ["LICENSE", "LICENCE", "COPYING", "UNLICENSE", "NOTICE", "COPYRIGHT"]
                .iter()
                .any(|p| upper.starts_with(p))
                .then(|| (name, read_text(&e.path())))
        })
        .collect();
    files.sort();
    for (chosen, others) in &parts {
        let has = |license: &str| files.iter().any(|(name, _)| name.to_uppercase().contains(&file_word(license)));
        if has(chosen) {
            files.retain(|(name, _)| {
                let upper = name.to_uppercase();
                upper.contains(&file_word(chosen)) || !others.iter().any(|o| upper.contains(&file_word(o)))
            });
        }
    }
    if !files.is_empty() {
        return Ok(files
            .iter()
            .map(|(name, text)| format!("--- {name} ---\n\n{text}"))
            .collect::<Vec<_>>()
            .join("\n\n"));
    }
    let mut texts = Vec::new();
    for (chosen, _) in parts.iter().filter(|(c, _)| !FONT_LICENSES.contains(&c.as_str())) {
        texts.push(match chosen.as_str() {
            "MIT" => format!("MIT License\n\nCopyright (c) {authors}\n\n{MIT}"),
            "BSL-1.0" => format!("Copyright (c) {authors}\n\n{BSL}"),
            "Apache-2.0" => format!("Copyright {authors}\n\n{apache}"),
            other => return Err(other.to_owned()),
        });
    }
    Ok(format!(
        "The package includes no license file; this is the standard text of its license with its declared authors.\n\n{}",
        texts.join("\n\n")
    ))
}

/// For each part of an SPDX expression joined by AND: the license Rocket uses (MIT when
/// offered, otherwise the first choice) and the choices it leaves.
fn choices(expression: &str) -> Vec<(String, Vec<String>)> {
    expression
        .split(" AND ")
        .map(|part| {
            let options: Vec<String> = part
                .trim_matches(|c: char| c == '(' || c == ')' || c.is_whitespace())
                .split(" OR ")
                .flat_map(|o| o.split('/'))
                .map(|o| o.trim().to_owned())
                .collect();
            let chosen = if options.iter().any(|o| o == "MIT") { "MIT".to_owned() } else { options[0].clone() };
            let others = options.into_iter().filter(|o| *o != chosen).collect();
            (chosen, others)
        })
        .collect()
}

/// How a license's file is usually named: LICENSE-MIT, LICENSE-APACHE, UNLICENSE…
fn file_word(license: &str) -> String {
    match license {
        "Apache-2.0" => "APACHE".into(),
        "Unicode-3.0" => "UNICODE".into(),
        "BSL-1.0" => "BOOST".into(),
        "GPL-2.0-only" => "GPL".into(),
        other => other.split('-').next().unwrap_or(other).to_uppercase(),
    }
}

/// egui's fonts, each with the notice its crate ships for it, on its crate's platforms.
fn egui_fonts(directory: &Path, version: &str, platforms: &str) -> Vec<Entry> {
    let fonts = directory.join("fonts");
    let present: BTreeSet<String> = fs::read_dir(&fonts)
        .expect("egui's fonts folder")
        .flatten()
        .map(|e| e.file_name().to_string_lossy().into_owned())
        .filter(|name| name.ends_with(".ttf"))
        .collect();
    let known: BTreeSet<String> = FONTS.iter().map(|f| f.0.to_owned()).collect();
    assert_eq!(present, known, "egui's fonts changed; update FONTS with their licenses");
    FONTS
        .iter()
        .map(|&(_, notice, name, license)| Entry {
            kind: "font",
            name: name.to_owned(),
            version: format!("from epaint_default_fonts {version}"),
            license: license.to_owned(),
            platforms: platforms.to_owned(),
            source: "https://github.com/emilk/egui".to_owned(),
            text: read_text(&fonts.join(notice)),
        })
        .collect()
}

/// The reviewed ConPTY runtime shipped beside Rocket on Windows, with Microsoft's license.
fn conpty(root: &Path) -> Entry {
    let base = root.join("runtime").join("conpty");
    let versions: Vec<String> = fs::read_dir(&base)
        .expect("the ConPTY runtime folder")
        .flatten()
        .filter(|e| e.file_type().is_ok_and(|t| t.is_dir()))
        .map(|e| e.file_name().to_string_lossy().into_owned())
        .collect();
    assert_eq!(versions.len(), 1, "one reviewed ConPTY runtime");
    let version = versions[0].clone();
    Entry {
        kind: "runtime",
        name: "Microsoft ConPTY".to_owned(),
        text: read_text(&base.join(&version).join("LICENSE")),
        source: format!("https://www.nuget.org/packages/Microsoft.Windows.Console.ConPTY/{version}"),
        version,
        license: "MIT".to_owned(),
        platforms: "Windows".to_owned(),
    }
}

fn render(entries: &[Entry]) -> String {
    let targets = TARGETS.map(|(platform, target)| format!("{target} ({platform})")).join(" and ");
    let mut out = format!(
        "Third-party notices for Rocket\n\n\
         Rocket includes the software below. Each entry names its license and the platforms\n\
         whose builds include it, and carries the notice its authors ship with it. Where a\n\
         crate offers MIT among other licenses, Rocket uses it under MIT. Generated from\n\
         Cargo.lock for {targets} by\n\
         `cargo run -p rocket-ui --example third_party_notices`; do not edit by hand.\n"
    );
    for e in entries {
        assert!(!e.text.contains(SEPARATOR), "{} has a line the Legal page splits on", e.name);
        out.push_str(&format!(
            "\n{SEPARATOR}\nKind: {}\nName: {}\nVersion: {}\nLicense: {}\nPlatforms: {}\nSource: {}\n{SEPARATOR}\n\n{}\n",
            e.kind, e.name, e.version, e.license, e.platforms, e.source, e.text
        ));
    }
    out
}

/// A text file with Windows line endings and trailing space removed.
fn read_text(path: &Path) -> String {
    let bytes = fs::read(path).unwrap_or_else(|e| panic!("read {}: {e}", path.display()));
    String::from_utf8_lossy(&bytes)
        .replace("\r\n", "\n")
        .lines()
        .map(str::trim_end)
        .collect::<Vec<_>>()
        .join("\n")
        .trim()
        .to_owned()
}

fn array(value: &Value) -> &[Value] {
    value.as_array().map(Vec::as_slice).unwrap_or_default()
}

fn string(value: &Value) -> &str {
    value.as_str().unwrap_or_default()
}
