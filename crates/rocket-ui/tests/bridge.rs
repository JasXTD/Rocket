fn wait(app: &mut Rocket, ctx: &eframe::egui::Context) {
    let deadline = Instant::now() + Duration::from_secs(40);
    while app.busy() {
        app.poll(ctx);
        assert!(Instant::now() < deadline, "UI worker timeout");
        thread::sleep(Duration::from_millis(10));
    }
}

#[test]
fn diff_selection_reuses_repository_setup_but_reads_fresh_content() {
    common::isolated(
        "ROCKET_UI_TEST_CASE",
        "diff_selection_reuses_repository_setup_but_reads_fresh_content",
        || {
            let f = Fixture::new();
            f.write("private [literal].rs", "base\n");
            f.commit("base");
            f.write("private [literal].rs", "staged\n");
            f.run(&["--literal-pathspecs", "add", "--", "private [literal].rs"]);
            f.write("private [literal].rs", "first edit\n");
            let ctx = eframe::egui::Context::default();
            let logs = f.root.join("diff-logs");
            let mut app =
                Rocket::with_log_directory(&ctx, vec![f.repository.clone()], logs.clone());
            wait(&mut app, &ctx);
            // Measure explicit diff selections independently from notifications
            // generated by this test's external edits (covered in refresh_state).
            app.auto_refresh = false;
            app.poll(&ctx);
            wait(&mut app, &ctx);
            // Composer loading is deliberately nonblocking for the UI. Wait for
            // that unrelated startup read before counting explicit diff commands.
            let deadline = Instant::now() + Duration::from_secs(40);
            while app.tab().is_some_and(|t| t.composer.running() || t.composer.needs_read) {
                app.poll(&ctx);
                assert!(Instant::now() < deadline, "composer startup timeout");
                thread::sleep(Duration::from_millis(10));
            }
            let commit = app.tab().unwrap().commits()[0].id.clone();
            let entry = app
                .tab()
                .unwrap()
                .snapshot
                .as_ref()
                .unwrap()
                .status
                .as_ref()
                .unwrap()
                .entries[0]
                .clone();
            let before = std::fs::read_to_string(logs.join("rocket.jsonl")).unwrap();
            let mut expected_commands = 0;
            for (staged, text) in [
                (true, "+staged"),
                (false, "+first edit"),
                (false, "+second edit"),
            ] {
                if text == "+second edit" {
                    f.write("private [literal].rs", "second edit\n");
                }
                app.dispatch(Intent::SelectChange(entry.clone(), staged));
                wait(&mut app, &ctx);
                assert!(
                    app.tab().unwrap().patch_error.is_none(),
                    "{:?}",
                    app.tab().unwrap().patch_error
                );
                let patch = app.tab().unwrap().patch.as_ref().unwrap();
                assert!(patch.files[0].lines.iter().any(|l| l.text == text));
                expected_commands += 1;
            }
            app.dispatch(Intent::SelectCommit(commit));
            wait(&mut app, &ctx);
            assert!(
                app.tab().unwrap().patch.as_ref().unwrap().files[0]
                    .lines
                    .iter()
                    .any(|l| l.text == "+base")
            );
            // The commit patch and exact file identities are separate reads.
            // File actions bind to raw Git metadata, never parsed display labels.
            expected_commands += 2;
            let after = std::fs::read_to_string(logs.join("rocket.jsonl")).unwrap();
            let diff_log = after.strip_prefix(&before).unwrap();
            let commands: Vec<_> = diff_log
                .lines()
                .filter(|line| line.contains("\"event\":\"git_start\""))
                .collect();
            assert_eq!(
                commands.len(),
                expected_commands,
                "diff selection must not rediscover Git/repository:\n{diff_log}"
            );
            assert_eq!(
                commands
                    .iter()
                    .filter(|line| line.contains("\"operation\":\"diff\""))
                    .count(),
                3
            );
            assert_eq!(
                commands
                    .iter()
                    .filter(|line| line.contains("\"operation\":\"show\""))
                    .count(),
                2
            );
            assert_eq!(
                commands
                    .iter()
                    .filter(|line| line.contains("\"operation\":\"rev-parse\""))
                    .count(),
                0
            );
            assert!(!diff_log.contains("verify_git"));
            assert!(!diff_log.contains("repository_discovery"));
            assert_eq!(diff_log.matches("\"event\":\"request_start\"").count(), 4);
            assert_eq!(diff_log.matches("\"event\":\"request_end\"").count(), 4);
            assert!(!diff_log.contains("private [literal]"));
            assert!(!diff_log.contains("second edit"));
            assert_eq!(app.backend.as_ref().unwrap().log.health().dropped_events, 0);
        },
    );
}

#[test]
fn gui_bridge_preserves_partial_staging_reports_hook_failure_and_keeps_logs_private() {
    common::isolated(
        "ROCKET_UI_TEST_CASE",
        "gui_bridge_preserves_partial_staging_reports_hook_failure_and_keeps_logs_private",
        || {
            let f = Fixture::new();
            f.write("private [literal].rs", "base\n");
            f.commit("initial");
            f.write("private [literal].rs", "staged\n");
            let backend = Backend::discover(&f.root.join("logs")).unwrap();
            let (tx, _rx) = mpsc::sync_channel(16);
            let token = CancellationToken::new();
            let path = RepoPath::new(b"private [literal].rs".to_vec()).unwrap();
            assert!(
                backend
                    .execute(
                        &f.repository,
                        &Action::Stage(vec![path.clone()]),
                        &tx,
                        &token
                    )
                    .unwrap()
                    .command_succeeded
            );
            f.write("private [literal].rs", "unstaged\n");
            let snapshot = backend
                .snapshot(&f.repository, HistoryStart::Head, &token)
                .unwrap();
            let entry = &snapshot.status.unwrap().entries[0];
            assert_eq!(entry.index, Change::Modified);
            assert_eq!(entry.worktree, Change::Modified);
            let patch = backend
                .diff(
                    &snapshot.repository,
                    &DiffOptions {
                        target: DiffTarget::Staged,
                        paths: vec![path],
                        ..Default::default()
                    },
                    &token,
                )
                .unwrap();
            assert!(patch.files[0].lines.iter().any(|l| l.text == "+staged"));
            assert!(!patch.files[0].lines.iter().any(|l| l.text == "+unstaged"));
            let outcome = backend
                .execute(
                    &f.repository,
                    &Action::Commit("ROCKET_PRIVATE_message".into()),
                    &tx,
                    &token,
                )
                .unwrap();
            assert!(outcome.command_succeeded);
            let status = f.repo().status(&token).unwrap();
            assert_eq!(status.entries[0].index, Change::Unchanged);
            assert_eq!(status.entries[0].worktree, Change::Modified);
            std::fs::write(
                f.root.join("no-hooks/pre-commit"),
                "#!/bin/sh\necho ROCKET_PRIVATE_hook >&2\nexit 1\n",
            )
            .unwrap();
            backend
                .execute(&f.repository, &Action::StageAll, &tx, &token)
                .unwrap();
            let rejected = backend
                .execute(&f.repository, &Action::Commit("reject".into()), &tx, &token)
                .unwrap();
            assert!(!rejected.command_succeeded);
            assert!(rejected.raw_output.contains("ROCKET_PRIVATE_hook"));
            assert!(!rejected.details.join(" ").contains("ROCKET_PRIVATE_hook"));
            let log = std::fs::read_to_string(f.root.join("logs/rocket.jsonl")).unwrap();
            assert!(!log.contains("ROCKET_PRIVATE"));
            assert!(!log.contains("private [literal]"));
            assert!(log.contains("request_start"));
        },
    );
}

#[test]
fn controller_keeps_drafts_on_failure_and_discards_superseded_diff_results() {
    common::isolated(
        "ROCKET_UI_TEST_CASE",
        "controller_keeps_drafts_on_failure_and_discards_superseded_diff_results",
        || {
            let f = Fixture::new();
            f.write("a.rs", "base\n");
            f.commit("initial");
            f.write("a.rs", "new\n");
            let ctx = eframe::egui::Context::default();
            let mut app = Rocket::with_log_directory(
                &ctx,
                vec![f.repository.clone()],
                f.root.join("ui-logs"),
            );
            wait(&mut app, &ctx);
            assert!(app.tab().unwrap().error.is_none());
            let id = app.tab().unwrap().id;
            let commit = app.tab().unwrap().commits()[0].id.clone();
            app.dispatch(Intent::SelectCommit(commit));
            app.dispatch(Intent::View(View::Changes));
            assert!(
                app.tab().unwrap().patch.is_none(),
                "commit diff must not survive a switch to unselected Changes"
            );
            let entry = app
                .tab()
                .unwrap()
                .snapshot
                .as_ref()
                .unwrap()
                .status
                .as_ref()
                .unwrap()
                .entries[0]
                .clone();
            app.dispatch(Intent::SelectChange(entry, false));
            wait(&mut app, &ctx);
            assert!(
                app.tab().unwrap().patch.as_ref().unwrap().files[0]
                    .lines
                    .iter()
                    .any(|l| l.text == "+new")
            );
            app.tabs[0].draft = "keep this failed draft".into();
            app.execute(id, Action::Commit("keep this failed draft".into()));
            app.execute(id, Action::StageAll); // Reentry is refused while a write is active.
            wait(&mut app, &ctx);
            assert!(!app.activities.last().unwrap().outcome.command_succeeded);
            assert_eq!(app.tab().unwrap().draft, "keep this failed draft");
            assert_eq!(
                app.tab()
                    .unwrap()
                    .snapshot
                    .as_ref()
                    .unwrap()
                    .status
                    .as_ref()
                    .unwrap()
                    .entries[0]
                    .index,
                Change::Unchanged
            );
            app.dispatch(Intent::CloseTab(id));
            assert!(app.dialog.is_some());
            assert_eq!(app.tabs.len(), 1);
        },
    );
}

#[test]
fn cancelling_on_exit_keeps_the_draft_and_waits_for_the_write_report() {
    common::isolated(
        "ROCKET_UI_TEST_CASE",
        "cancelling_on_exit_keeps_the_draft_and_waits_for_the_write_report",
        || {
            let f = Fixture::new();
            f.write("a.rs", "base\n");
            f.commit("initial");
            let before = f.repo().head(&CancellationToken::new()).unwrap();
            f.write("a.rs", "staged\n");
            let staged = f.repo().stage_all(&CancellationToken::new()).unwrap();
            staged.result.unwrap();
            staged.status.unwrap();
            std::fs::write(
                f.root.join("no-hooks/pre-commit"),
                "#!/bin/sh\nprintf ready > .git/ui-hook-ready\nsleep 30\n",
            )
            .unwrap();
            let ctx = eframe::egui::Context::default();
            let mut app = Rocket::with_log_directory(
                &ctx,
                vec![f.repository.clone()],
                f.root.join("ui-logs"),
            );
            wait(&mut app, &ctx);
            let id = app.tab().unwrap().id;
            app.tabs[0].draft = "keep the cancelled draft".into();
            app.execute(id, Action::Commit(app.tabs[0].draft.clone()));
            let deadline = Instant::now() + Duration::from_secs(20);
            while !f.repository.join(".git/ui-hook-ready").exists() {
                app.poll(&ctx);
                assert!(
                    app.write.is_some(),
                    "commit ended before reaching the test hook"
                );
                assert!(Instant::now() < deadline, "test hook was not reached");
                thread::sleep(Duration::from_millis(10));
            }
            app.begin_quit();
            assert!(app.busy(), "exit must wait for the active write report");
            app.open(f.root.join("must-not-open-during-exit"));
            assert_eq!(app.tabs.len(), 1);
            wait(&mut app, &ctx);
            assert!(app.quitting);
            assert_eq!(app.activities.len(), 1);
            assert!(!app.activities[0].outcome.command_succeeded);
            assert!(
                app.activities[0]
                    .outcome
                    .details
                    .iter()
                    .any(|s| s.to_lowercase().contains("cancel"))
            );
            assert_eq!(app.tabs[0].draft, "keep the cancelled draft");
            assert_eq!(f.repo().head(&CancellationToken::new()).unwrap(), before);
            assert_eq!(
                f.repo().status(&CancellationToken::new()).unwrap().entries[0].index,
                Change::Modified
            );
        },
    );
}

#[test]
fn ui_routes_local_clone_fetch_push_and_pull_and_refuses_existing_files() {
    common::isolated(
        "ROCKET_UI_TEST_CASE",
        "ui_routes_local_clone_fetch_push_and_pull_and_refuses_existing_files",
        || {
            let f = Fixture::new();
            f.write("initial.rs", "base\n");
            f.commit("initial");
            let remote = f.root.join("upstream.git");
            let create = f
                .command(
                    &f.root,
                    &[
                        "init",
                        "--bare",
                        "--initial-branch=main",
                        remote.to_str().unwrap(),
                    ],
                )
                .output()
                .unwrap();
            assert!(create.status.success());
            f.run(&["remote", "add", "origin", remote.to_str().unwrap()]);
            let backend = Backend::discover(&f.root.join("logs")).unwrap();
            let token = CancellationToken::new();
            let (tx, _rx) = mpsc::sync_channel(16);
            let push = backend
                .execute(
                    &f.repository,
                    &Action::Push {
                        remote: b"origin".to_vec(),
                        local: b"main".to_vec(),
                        destination: b"main".to_vec(),
                        set_upstream: true,
                    },
                    &tx,
                    &token,
                )
                .unwrap();
            assert!(push.command_succeeded);
            assert_eq!(push.summary, "Remote update confirmed");
            assert!(push.details.is_empty());
            let destination = f.root.join("clone destination");
            let (clone_tx, _clone_rx) = mpsc::sync_channel(32);
            let cloned = backend
                .clone_repository(
                    CloneSource::Local(remote),
                    destination.clone(),
                    &clone_tx,
                    &token,
                )
                .unwrap();
            assert!(cloned.command_succeeded);
            assert_eq!(cloned.open_repository.as_ref(), Some(&destination));
            assert!(cloned.details.is_empty());
            for args in [
                &["config", "user.name", "UI Test"][..],
                &["config", "user.email", "ui@example.invalid"][..],
                &["config", "commit.gpgsign", "false"][..],
            ] {
                assert!(
                    f.command(&destination, args)
                        .output()
                        .unwrap()
                        .status
                        .success()
                );
            }
            std::fs::write(destination.join("remote.rs"), "new remote content\n").unwrap();
            assert!(
                backend
                    .execute(&destination, &Action::StageAll, &tx, &token)
                    .unwrap()
                    .command_succeeded
            );
            assert!(
                backend
                    .execute(
                        &destination,
                        &Action::Commit("Remote UI test commit".into()),
                        &tx,
                        &token
                    )
                    .unwrap()
                    .command_succeeded
            );
            assert!(
                backend
                    .execute(
                        &destination,
                        &Action::Push {
                            remote: b"origin".to_vec(),
                            local: b"main".to_vec(),
                            destination: b"main".to_vec(),
                            set_upstream: false
                        },
                        &tx,
                        &token
                    )
                    .unwrap()
                    .command_succeeded
            );
            assert!(
                backend
                    .execute(
                        &f.repository,
                        &Action::Fetch(b"origin".to_vec()),
                        &tx,
                        &token
                    )
                    .unwrap()
                    .command_succeeded
            );
            let pull = backend
                .execute(&f.repository, &Action::Pull, &tx, &token)
                .unwrap();
            assert!(pull.command_succeeded);
            assert!(pull.details.is_empty());
            assert_eq!(
                std::fs::read_to_string(f.repository.join("remote.rs")).unwrap(),
                "new remote content\n"
            );
            let rejected = backend.clone_repository(
                CloneSource::Local(f.repository.clone()),
                destination.clone(),
                &clone_tx,
                &token,
            );
            assert!(rejected.is_err());
            assert_eq!(
                std::fs::read_to_string(destination.join("remote.rs")).unwrap(),
                "new remote content\n"
            );
        },
    );
}

#[test]
fn ui_routes_branch_stash_and_merge_reports() {
    common::isolated(
        "ROCKET_UI_TEST_CASE",
        "ui_routes_branch_stash_and_merge_reports",
        || {
            let f = Fixture::new();
            f.write("base.rs", "base\n");
            f.commit("initial");
            let backend = Backend::discover(&f.root.join("logs")).unwrap();
            let token = CancellationToken::new();
            let (tx, _rx) = mpsc::sync_channel(16);
            let run = |action| {
                let result = backend
                    .execute(&f.repository, &action, &tx, &token)
                    .unwrap();
                assert!(result.command_succeeded, "{:?}", result.details);
                assert!(result.details.is_empty());
            };
            run(Action::CreateBranch("feature/ui".into()));
            run(Action::SwitchBranch(b"feature/ui".to_vec()));
            f.write("feature.rs", "feature\n");
            run(Action::StageAll);
            run(Action::Commit("feature".into()));
            run(Action::SwitchBranch(b"main".to_vec()));
            run(Action::Merge {
                target: "feature/ui".into(),
                mode: MergeMode::FastForwardOnly,
            });
            run(Action::RenameBranch(
                b"feature/ui".to_vec(),
                "feature/merged".into(),
            ));
            run(Action::DeleteBranch(b"feature/merged".to_vec()));
            f.write("base.rs", "saved edit\n");
            run(Action::Stash {
                message: "UI stash".into(),
                include_untracked: false,
                paths: Vec::new(),
            });
            let entry = backend
                .snapshot(&f.repository, HistoryStart::Head, &token)
                .unwrap()
                .stashes
                .remove(0);
            run(Action::ApplyStash {
                entry: entry.clone(),
                restore_index: false,
            });
            run(Action::DropStash(entry));
            assert_eq!(
                std::fs::read_to_string(f.repository.join("base.rs")).unwrap(),
                "saved edit\n"
            );
        },
    );
}
